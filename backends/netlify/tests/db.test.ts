// Runs the real migrations and SQL against a local Netlify Database (PGlite). Expected behaviour
// comes from the merged-hours contract in supabase/bootstrap/002 section 5 ("the hour's per-device
// rows are deleted and the merged row written in ONE transaction"; a per-device row belongs to the
// hour its started_at falls in) and from docs/adr/0001 and src/keys.ts (a Device key is shown once,
// stored only as a hash, revocable, and scoped to one person). A merged hour of 0 or less is
// skipped: it is not written, deletes nothing, and leaves a stored merged value as it was, while
// the rest of the batch is stored (src/ingest.ts). The setup secret is generated by a migration,
// never chosen or shown by the site; the Owner reads it in the Netlify UI (README "Set up").

import { afterAll, beforeAll, beforeEach, describe, expect, test } from 'vitest'
import { NetlifyDB } from '@netlify/database-dev'
import pg from 'pg'
import { hashDeviceKey } from '../src/keys.ts'
import {
  ensureOwner, issueDeviceKey, listDeviceKeys, personForDeviceKey, replaceMergedHours,
  revokeDeviceKey, upsertDeviceRows,
} from '../src/store.ts'
import { handleSetup } from '../src/setup.ts'
import { handleIngest } from '../src/ingest.ts'

const STEPS = 'HKQuantityTypeIdentifierStepCount'

/** The setup secret as the Owner reads it: straight from the table, as the Netlify UI shows it. */
async function storedSecret(): Promise<string | undefined> {
  const { rows } = await pool.query<{ secret: string }>('SELECT secret FROM setup_secret')
  return rows[0]?.secret
}

let db: NetlifyDB
let pool: pg.Pool

beforeAll(async () => {
  db = new NetlifyDB({ logger: () => {} })
  const connectionString = await db.start()
  await db.applyMigrations('./netlify/database/migrations')
  pool = new pg.Pool({ connectionString, max: 1 })
})

afterAll(async () => {
  await pool?.end()
  await db?.stop()
})

beforeEach(async () => {
  await pool.query('TRUNCATE healthkit_metrics, healthkit_daily_summaries, device_keys, people CASCADE')
})

const row = (userId: string, over: Record<string, unknown> = {}) => ({
  user_id: userId, metric_type: STEPS, value: 100, unit: 'count', source_device: 'iPhone',
  started_at: '2026-10-01T08:10:00Z', ended_at: '2026-10-01T08:15:00Z', metadata: null, ...over,
})

describe('schema', () => {
  test('the tables the Python MCP server queries exist with the columns it reads', async () => {
    const { rows } = await pool.query(
      `SELECT table_name, column_name FROM information_schema.columns
        WHERE table_name IN ('healthkit_metrics', 'healthkit_daily_summaries')
          AND column_name IN ('user_id', 'metric_type', 'started_at', 'summary_date', 'source_device')`,
    )
    const got = rows.map((r) => `${r.table_name}.${r.column_name}`).sort()
    expect(got).toEqual([
      'healthkit_daily_summaries.metric_type', 'healthkit_daily_summaries.summary_date',
      'healthkit_daily_summaries.user_id', 'healthkit_metrics.metric_type',
      'healthkit_metrics.source_device', 'healthkit_metrics.started_at', 'healthkit_metrics.user_id',
    ])
  })
})

describe('owner and device keys', () => {
  test('ensureOwner creates one Owner and returns the same ID every time', async () => {
    const a = await ensureOwner(pool)
    const b = await ensureOwner(pool)
    expect(a).toBe(b)
    const { rows } = await pool.query('SELECT count(*)::int AS n FROM people WHERE is_owner')
    expect(rows[0].n).toBe(1)
  })

  test('a key is stored only as its hash and resolves to its person until revoked', async () => {
    const owner = await ensureOwner(pool)
    const issued = await issueDeviceKey(pool, owner, 'iPhone')
    const { rows } = await pool.query('SELECT key_hash FROM device_keys')
    expect(rows[0].key_hash).toBe(hashDeviceKey(issued.key))
    expect(JSON.stringify(rows)).not.toContain(issued.key)

    expect(await personForDeviceKey(pool, issued.key)).toBe(owner)
    expect(await personForDeviceKey(pool, issued.key + 'x')).toBeNull()

    expect(await revokeDeviceKey(pool, owner, issued.id)).toBe(true)
    expect(await personForDeviceKey(pool, issued.key)).toBeNull()
    expect(await revokeDeviceKey(pool, owner, issued.id)).toBe(false)
  })

  test('last_used_at is refreshed at most once an hour', async () => {
    const owner = await ensureOwner(pool)
    const issued = await issueDeviceKey(pool, owner, 'iPhone')
    await pool.query(`UPDATE device_keys SET last_used_at = '2026-01-01T00:00:00Z'`)
    await personForDeviceKey(pool, issued.key)
    const first = (await listDeviceKeys(pool, owner))[0].last_used_at
    expect(new Date(first!).getTime()).toBeGreaterThan(Date.parse('2026-01-01T00:00:01Z'))
    await personForDeviceKey(pool, issued.key)
    const second = (await listDeviceKeys(pool, owner))[0].last_used_at
    expect(new Date(second!).getTime()).toBe(new Date(first!).getTime())
  })

  test('using a key records last_used_at', async () => {
    const owner = await ensureOwner(pool)
    const issued = await issueDeviceKey(pool, owner, 'iPhone')
    await personForDeviceKey(pool, issued.key)
    const [listed] = await listDeviceKeys(pool, owner)
    expect(listed.last_used_at).not.toBeNull()
  })
})

describe('storage', () => {
  test('upsert overwrites the same (metric, device, instant) and keeps other devices', async () => {
    const owner = await ensureOwner(pool)
    await upsertDeviceRows(pool, [row(owner), row(owner, { source_device: 'Apple Watch' })])
    await upsertDeviceRows(pool, [row(owner, { value: 250 })])
    const { rows } = await pool.query('SELECT source_device, value FROM healthkit_metrics ORDER BY source_device')
    expect(rows).toEqual([{ source_device: 'Apple Watch', value: 100 }, { source_device: 'iPhone', value: 250 }])
  })

  test('a merged hour deletes that hour\'s per-device rows only, and is idempotent', async () => {
    const owner = await ensureOwner(pool)
    await upsertDeviceRows(pool, [
      row(owner, { started_at: '2026-10-01T08:00:00Z' }),
      row(owner, { started_at: '2026-10-01T08:59:59Z', source_device: 'Apple Watch' }),
      row(owner, { started_at: '2026-10-01T09:00:00Z' }), // next hour: stays
      row(owner, { started_at: '2026-10-01T08:30:00Z', metric_type: 'HKQuantityTypeIdentifierHeartRate' }), // other type: stays
    ])
    const merged = [{
      metric_type: STEPS, value: 1200, unit: 'count', metadata: null,
      started_at: '2026-10-01T08:00:00.000Z', ended_at: '2026-10-01T09:00:00.000Z',
    }]
    expect(await replaceMergedHours(pool, owner, merged)).toEqual({ written: 1, deleted: 2 })
    expect(await replaceMergedHours(pool, owner, merged)).toEqual({ written: 1, deleted: 0 })

    const { rows } = await pool.query(
      `SELECT metric_type, source_device, to_char(started_at AT TIME ZONE 'UTC', 'HH24:MI') AS t, value
         FROM healthkit_metrics ORDER BY metric_type, started_at, source_device`,
    )
    expect(rows).toEqual([
      { metric_type: 'HKQuantityTypeIdentifierHeartRate', source_device: 'iPhone', t: '08:30', value: 100 },
      { metric_type: STEPS, source_device: 'HealthKit (all sources)', t: '08:00', value: 1200 },
      { metric_type: STEPS, source_device: 'iPhone', t: '09:00', value: 100 },
    ])
  })
})

describe('ingest end to end against the database', () => {
  test('a minted key ingests a batch; the stored user_id is the Owner', async () => {
    const owner = await ensureOwner(pool)
    const { key } = await issueDeviceKey(pool, owner, 'iPhone')
    const res = await handleIngest(
      new Request('https://example.test/api/ingest', {
        method: 'POST',
        headers: { Authorization: `Bearer ${key}` },
        body: JSON.stringify({ samples: [
          { metric_type: 'HKQuantityTypeIdentifierHeartRate', value: 58, unit: 'count/min', source_device: 'Apple Watch', started_at: '2026-10-01T03:00:00Z' },
          { metric_type: STEPS, value: 900, unit: 'count', source_device: 'HealthKit (all sources)', started_at: '2026-10-01T08:00:00Z', ended_at: '2026-10-01T09:00:00Z' },
        ] }),
      }),
      {
        authenticate: (k) => personForDeviceKey(pool, k),
        upsertDeviceRows: (rows) => upsertDeviceRows(pool, rows),
        replaceMergedHours: (u, rows) => replaceMergedHours(pool, u, rows),
      },
    )
    expect(res.status).toBe(200)
    expect(await res.json()).toEqual({ inserted: 2, replaced: 0, capabilities: ['merged_hours_v1'] })
    const { rows } = await pool.query('SELECT DISTINCT user_id FROM healthkit_metrics')
    expect(rows).toEqual([{ user_id: owner }])
  })
})

describe('a merged hour of 0 or less against the database', () => {
  const MERGED = 'HealthKit (all sources)'
  const mergedSample = (over: Record<string, unknown> = {}) => ({
    metric_type: STEPS, value: 0, unit: 'count', source_device: MERGED,
    started_at: '2026-10-01T08:00:00Z', ended_at: '2026-10-01T09:00:00Z', ...over,
  })

  async function ingest(samples: unknown[]) {
    const owner = await ensureOwner(pool)
    const { key } = await issueDeviceKey(pool, owner, 'iPhone')
    const res = await handleIngest(
      new Request('https://example.test/api/ingest', {
        method: 'POST',
        headers: { Authorization: `Bearer ${key}` },
        body: JSON.stringify({ samples }),
      }),
      {
        authenticate: (k) => personForDeviceKey(pool, k),
        upsertDeviceRows: (rows) => upsertDeviceRows(pool, rows),
        replaceMergedHours: (u, rows) => replaceMergedHours(pool, u, rows),
      },
    )
    return { status: res.status, body: await res.json() }
  }

  async function storedSteps() {
    const { rows } = await pool.query(
      `SELECT source_device, to_char(started_at AT TIME ZONE 'UTC', 'HH24:MI') AS t, value
         FROM healthkit_metrics WHERE metric_type = $1 ORDER BY started_at, source_device`,
      [STEPS],
    )
    return rows
  }

  const skippedOne = { inserted: 0, replaced: 0, skipped_merged_hours: 1, capabilities: ['merged_hours_v1'] }

  test('a 0 leaves the hour\'s per-device rows in place and writes nothing', async () => {
    const owner = await ensureOwner(pool)
    await upsertDeviceRows(pool, [
      row(owner, { started_at: '2026-10-01T08:10:00Z' }),
      row(owner, { started_at: '2026-10-01T08:40:00Z', source_device: 'Apple Watch', value: 250 }),
    ])
    expect(await ingest([mergedSample()])).toEqual({ status: 200, body: skippedOne })
    expect(await storedSteps()).toEqual([
      { source_device: 'iPhone', t: '08:10', value: 100 },
      { source_device: 'Apple Watch', t: '08:40', value: 250 },
    ])
  })

  test('a 0 leaves a stored merged value for that hour unchanged', async () => {
    const owner = await ensureOwner(pool)
    await replaceMergedHours(pool, owner, [{
      metric_type: STEPS, value: 1200, unit: 'count', metadata: null,
      started_at: '2026-10-01T08:00:00.000Z', ended_at: '2026-10-01T09:00:00.000Z',
    }])
    expect(await ingest([mergedSample()])).toEqual({ status: 200, body: skippedOne })
    expect(await storedSteps()).toEqual([{ source_device: MERGED, t: '08:00', value: 1200 }])
  })

  test('in a mixed batch with a 0 and a negative, the device row and the real merged hour are stored and counted as before', async () => {
    const owner = await ensureOwner(pool)
    await upsertDeviceRows(pool, [
      row(owner, { started_at: '2026-10-01T08:10:00Z' }),
      row(owner, { started_at: '2026-10-01T08:40:00Z', source_device: 'Apple Watch' }),
      row(owner, { started_at: '2026-10-01T09:20:00Z' }),
      row(owner, { started_at: '2026-10-01T10:30:00Z' }),
    ])
    const result = await ingest([
      { metric_type: 'HKQuantityTypeIdentifierHeartRate', value: 58, unit: 'count/min', source_device: 'Apple Watch', started_at: '2026-10-01T03:00:00Z' },
      mergedSample({ value: 900 }),
      mergedSample({ started_at: '2026-10-01T09:00:00Z', ended_at: '2026-10-01T10:00:00Z' }),
      mergedSample({ value: -5, started_at: '2026-10-01T10:00:00Z', ended_at: '2026-10-01T11:00:00Z' }),
    ])
    // 1 heart-rate row + 1 merged row written; the 08:00 hour's 2 per-device rows replaced; the
    // 09:00 and 10:00 hours skipped.
    expect(result).toEqual({
      status: 200,
      body: { inserted: 2, replaced: 2, skipped_merged_hours: 2, capabilities: ['merged_hours_v1'] },
    })
    expect(await storedSteps()).toEqual([
      { source_device: MERGED, t: '08:00', value: 900 },
      { source_device: 'iPhone', t: '09:20', value: 100 },
      { source_device: 'iPhone', t: '10:30', value: 100 },
    ])
    const { rows } = await pool.query(`SELECT value FROM healthkit_metrics WHERE metric_type = 'HKQuantityTypeIdentifierHeartRate'`)
    expect(rows).toEqual([{ value: 58 }])
  })
})

describe('setup API', () => {
  // `secret` undefined sends the stored one, null sends no header.
  const call = async (path: string, init: RequestInit = {}, secret?: string | null) => {
    const presented = secret === undefined ? await storedSecret() : secret
    return handleSetup(
      new Request(`https://example.test${path}`, {
        ...init,
        headers: { ...(presented == null ? {} : { 'X-Setup-Secret': presented }), ...(init.headers ?? {}) },
      }),
      () => pool,
    )
  }

  test('the first deploy generates a random UUID (version 4) as the secret', async () => {
    const secret = await storedSecret()
    expect(secret).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
    expect((await call('/api/setup')).status).toBe(200)
  })

  test('a wrong secret is 403', async () => {
    expect((await call('/api/setup', {}, 'wrong')).status).toBe(403)
    expect((await call('/api/setup', {}, '')).status).toBe(403)
  })

  test('a request without a secret is refused before the database is touched', async () => {
    const res = await handleSetup(
      new Request('https://example.test/api/setup'),
      () => { throw new Error('database touched') },
    )
    expect(res.status).toBe(403)
  })

  test('no setup response contains the secret', async () => {
    const secret = (await storedSecret())!
    for (const res of [await call('/api/setup'), await call('/api/setup/keys'), await call('/api/setup', {}, 'wrong')]) {
      expect(await res.text()).not.toContain(secret)
    }
  })

  test('deleting the row replaces the secret: the old one stops working, a new one is stored', async () => {
    const old = (await storedSecret())!
    await pool.query('DELETE FROM setup_secret')
    expect((await call('/api/setup', {}, old)).status).toBe(403)
    const fresh = await storedSecret()
    expect(fresh).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
    expect(fresh).not.toBe(old)
    expect((await call('/api/setup')).status).toBe(200)
  })

  test('a secret the Owner types in must be at least 32 characters, and there is only ever one', async () => {
    await expect(pool.query("UPDATE setup_secret SET secret = 'too short'")).rejects.toThrow()
    await expect(pool.query("INSERT INTO setup_secret (secret) VALUES (repeat('x', 40))")).rejects.toThrow()
    await pool.query("UPDATE setup_secret SET secret = repeat('y', 32)")
    expect((await call('/api/setup', {}, 'y'.repeat(32))).status).toBe(200)
  })

  test('shows the Owner ID, never a connection string', async () => {
    const res = await call('/api/setup')
    const text = await res.text()
    expect(res.status).toBe(200)
    expect(JSON.parse(text).person_id).toBe(await ensureOwner(pool))
    expect(text).not.toMatch(/postgres(ql)?:\/\//)
  })

  test('issue, list, revoke', async () => {
    const issued = await (await call('/api/setup/keys', { method: 'POST', body: JSON.stringify({ label: 'iPhone' }) })).json()
    expect(issued.key).toMatch(/^h4a_/)
    const list = await (await call('/api/setup/keys')).json()
    expect(list.keys).toHaveLength(1)
    expect(JSON.stringify(list)).not.toContain(issued.key)
    expect((await call(`/api/setup/keys/${issued.id}/revoke`, { method: 'POST' })).status).toBe(204)
    expect((await call(`/api/setup/keys/${issued.id}/revoke`, { method: 'POST' })).status).toBe(404)
    expect((await call('/api/setup/keys/not-a-uuid/revoke', { method: 'POST' })).status).toBe(404)
  })
})
